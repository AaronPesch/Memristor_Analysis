r"""Build a folder of import cases, one per failure mode, for manual checking.

Usage:  python tools/make_error_cases.py <output_dir>

Each subfolder is meant to be imported from the app; the README written
alongside says which mode to use and what should appear. Two of the cases are
expected to succeed -- a failure demo is only convincing next to a control.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

import numpy as np
import xlsxwriter

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_fixtures  # noqa: E402

CYCLES = 5


def _device_into(target: Path, row: str, col: int, rng) -> None:
    """Generate one device's measurement files directly into `target`."""
    staging = target.parent / f".staging_{row}{col}"
    make_fixtures.build_device(staging, row, col, CYCLES, rng)
    produced = staging / make_fixtures.STACK_ID / f"{row}{col}"
    target.mkdir(parents=True, exist_ok=True)
    for item in produced.iterdir():
        shutil.move(str(item), target / item.name)
    shutil.rmtree(staging)


def case_no_excel_files(root: Path) -> None:
    folder = root / "1_no_excel_files"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "some_document.pdf").write_bytes(b"%PDF-1.4\n% not a spreadsheet\n")
    (folder / "readme.txt").write_text("No measurements here.\n", encoding="utf-8")


def case_stack_picked_as_device(root: Path, rng) -> None:
    folder = root / "2_stack_picked_as_device"
    for row, col in (("A", 1), ("A", 2)):
        _device_into(folder / f"{row}{col}", row, col, rng)


def case_no_run_sheets(root: Path) -> None:
    folder = root / "3_no_run_sheets"
    folder.mkdir(parents=True, exist_ok=True)
    book = xlsxwriter.Workbook(str(folder / "01 notes.xlsx"))
    sheet = book.add_worksheet("Tabelle1")
    sheet.write(0, 0, "voltage")
    sheet.write(1, 0, 1.2)
    book.close()


def case_unreadable_files(root: Path) -> None:
    folder = root / "4_unreadable_files"
    folder.mkdir(parents=True, exist_ok=True)
    # What a placeholder or a truncated download looks like: the name says
    # .xlsx, the content is not a zip container at all.
    for name in ("03 endurance set.xlsx", "04 endurance reset.xlsx"):
        (folder / name).write_bytes(b"\x00" * 64)


def case_works(root: Path, rng) -> None:
    _device_into(root / "5_works_device" / "A1", "A", 1, rng)


def case_quality_findings(root: Path, rng) -> None:
    """Imports fine, but the overview should have something to say."""
    stack = root / "6_quality_findings" / "STACK#9"
    _device_into(stack / "A1", "A", 1, rng)
    _device_into(stack / "A2", "A", 2, rng)
    # A byte-identical copy of A1 -- the duplicate check should group them.
    shutil.copytree(stack / "A1", stack / "A3")
    # A folder name that carries no grid position: invisible on the maps.
    _device_into(stack / "Temp_373K", "A", 4, rng)


README = """# Import error cases

Generated by `tools/make_error_cases.py`. Import each folder from the app and
compare the dialog with what is listed here.

| Folder | Import with | Expected |
|---|---|---|
| `1_no_excel_files` | Ctrl+O (device) | "No Excel files found matching", then the folder contents and the note that there are no spreadsheets anywhere below |
| `2_stack_picked_as_device` | Ctrl+O (device) | "No Excel files found matching", then "the .xlsx files sit one level down ... use Ctrl+Shift+O" naming A1 and A2 |
| `2_stack_picked_as_device` | Ctrl+Shift+O (stack) | succeeds -- the same folder, the right mode |
| `3_no_run_sheets` | Ctrl+O (device) | "contains no data", then "1 file(s) read: 0 with cycle data, 1 metadata only" and the hint about Run1, Run2 sheets |
| `4_unreadable_files` | Ctrl+O (device) | "contains no data", then two unreadable files and the placeholder/OneDrive hint |
| `5_works_device/A1` | Ctrl+O (device) | succeeds |
| `6_quality_findings` | Ctrl+Shift+O (stack) | succeeds; the overview reports A1 and A3 as holding identical data, and Temp_373K as having no grid position |

The measurements are synthetic, so the plots are meaningless -- these folders
are for checking the messages, not the physics.
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    parser.add_argument("--seed", type=int, default=5)
    args = parser.parse_args()

    root = args.output
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    rng = np.random.default_rng(args.seed)
    case_no_excel_files(root)
    case_stack_picked_as_device(root, rng)
    case_no_run_sheets(root)
    case_unreadable_files(root)
    case_works(root, rng)
    case_quality_findings(root, rng)
    (root / "README.md").write_text(README, encoding="utf-8")

    print(f"wrote {root}")
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        files = list(folder.rglob("*.*"))
        print(f"  {folder.name:28s} {len(files):3d} files")


if __name__ == "__main__":
    main()
